// Structured MCP tools for boards and sheets (#19): one shape or one cell changes, everything else stays byte for byte.
import assert from 'node:assert/strict';
import * as esbuild from 'esbuild';
const out = 'dist/test/board-sheet-tools.mjs';
await esbuild.build({ entryPoints: ['src/main/mcp-board-sheet.js'], bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error', loader: { '.md': 'text' }, banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" } });
const { runBoardSheetTool, BOARD_SHEET_TOOLS } = await import('../' + out);
const files = new Map();
const notes = { read: async (p) => { if (!files.has(p)) throw new Error('missing'); return files.get(p); }, write: async (p, t) => { files.set(p, t); return p; } };
const wrote = (p, verb) => `${verb} ${p}`;
const run = (name, a) => runBoardSheetTool(notes, name, a, wrote);
let n = 0; const ok = (m) => { n++; console.log('  ✓ ' + m); };
console.log('\nboard and sheet tools');

files.set('b.board.md', '# Arch\n\n```board\n// services\napi: component "Orders API" @400,100\ndb: cylinder "Orders DB" @640,100 {fill: #eee}\n\napi -> db "SQL"\n```\n\nNotes below.\n');
await run('add_shape', { path: 'b.board.md', id: 'cache', shape: 'rect', label: 'Cache', x: 400, y: 300 });
await run('connect', { path: 'b.board.md', from: 'api', to: 'cache', op: '-->', label: 'reads' });
let t = files.get('b.board.md');
assert(t.startsWith('# Arch\n\n```board\n// services\napi: component "Orders API" @400,100\ndb: cylinder "Orders DB" @640,100 {fill: #eee}'), t);
assert(t.includes('cache: rect "Cache" @400,300') && t.includes('api --> cache "reads"') && t.endsWith('```\n\nNotes below.\n'), t);
ok('add_shape and connect add lines; comments, other shapes and the text around the board stay');
const g = await run('get_board', { path: 'b.board.md' });
assert.deepEqual(g.shapes.map((s) => s.id), ['api', 'db', 'cache']); assert.equal(g.connectors.length, 2);
await run('update_shape', { path: 'b.board.md', id: 'db', label: 'Orders store', style: { fill: null, stroke: '#333' }, x: 700 });
assert(files.get('b.board.md').includes('db: cylinder "Orders store" @700,100 {stroke: #333}'), files.get('b.board.md'));
ok('update_shape changes label, position and style keys');
await run('add_shape', { path: 'b.board.md', id: 'queue1', shape: 'queue' });
assert((await run('get_board', { path: 'b.board.md' })).shapes.find((s) => s.id === 'queue1').x != null);
ok('a shape added without a position is placed by auto layout');
await assert.rejects(run('connect', { path: 'b.board.md', from: 'api', to: 'nope', op: '->' }), /No shape "nope"/);
await assert.rejects(run('add_shape', { path: 'b.board.md', id: 'api', shape: 'rect' }), /already exists/);
await run('remove_shape', { path: 'b.board.md', id: 'cache' });
t = files.get('b.board.md'); assert(!t.includes('cache'), t); assert(t.includes('api -> db "SQL"'));
await run('disconnect', { path: 'b.board.md', from: 'api', to: 'db' });
assert(!files.get('b.board.md').includes('api -> db'));
ok('remove_shape drops its connectors; disconnect removes one; unknown ids are refused');

files.set('s.sheet.md', '# Budget\n\n## Costs\n\n| Item | Cost |\n| ---- | ---- |\n| Rent | 800  |\n\n## Notes\n\n| A | B |\n| - | - |\n| x | y |\n\nEnd.\n');
await run('set_cells', { path: 's.sheet.md', sheet: 'Costs', cells: { B3: 120, A3: 'Food', B4: '=SUM(B2:B3)', A5: 'x|y' } });
t = files.get('s.sheet.md');
assert(t.includes('| Food') && t.includes('=SUM(B2:B3)') && t.includes('x\\|y'), t);
assert(t.includes('## Notes\n\n| A | B |\n| - | - |\n| x | y |\n\nEnd.\n'), t);
ok('set_cells writes values and formulas, grows the grid, and leaves other sheets byte for byte');
await assert.rejects(run('set_cells', { path: 's.sheet.md', cells: { '7B': 1 } }), /cell address/);
await assert.rejects(run('set_cells', { path: 's.sheet.md', sheet: 'Nope', cells: { A1: 1 } }), /No sheet named/);
await run('add_sheet', { path: 's.sheet.md', name: 'Totals', rows: [['What', 'Sum'], ['All', '=Costs!B4']] });
assert(files.get('s.sheet.md').includes('## Totals') && files.get('s.sheet.md').includes('=Costs!B4'));
await run('add_sheet', { path: 'new.sheet.md', name: 'First' });
assert(files.get('new.sheet.md').includes('## First'));
await assert.rejects(run('add_sheet', { path: 's.sheet.md', name: 'costs' }), /already exists/);
ok('add_sheet appends or creates; duplicate names and bad addresses are refused');
await assert.rejects(run('set_cells', { path: 'x.md', cells: { A1: 1 } }), /\.sheet\.md/);
const readers = ['get_board_reference', 'get_board', 'describe_board', 'find_shapes', 'list_shape_kinds', 'get_board_issues', 'render_board', 'export_board'];
assert.deepEqual(BOARD_SHEET_TOOLS.filter((t) => !t.write).map((t) => t.name).sort(), [...readers].sort());
assert(BOARD_SHEET_TOOLS.filter((t) => t.write).every((t) => !t.annotations.readOnlyHint));
ok('the tools refuse other file types and every write tool is marked as writing');
// CRLF files keep their endings; a board with unreadable lines is not rewritten
files.set('c.board.md', '# A\r\n\r\n```board\r\napi: rect "A" @0,0\r\ndb: rect "B" @200,0\r\n```\r\n\r\nEnd\r\n');
await run('connect', { path: 'c.board.md', from: 'api', to: 'db' });
assert.equal(files.get('c.board.md'), '# A\r\n\r\n```board\r\napi: rect "A" @0,0\r\ndb: rect "B" @200,0\r\n\r\napi -> db\r\n```\r\n\r\nEnd\r\n');
files.set('c.sheet.md', '## S\r\n\r\n| A | B |\r\n| - | - |\r\n| 1 | 2 |\r\n\r\nEnd\r\n');
await run('set_cells', { path: 'c.sheet.md', cells: { A2: 9 } });
assert(!/[^\r]\n/.test(files.get('c.sheet.md')) && files.get('c.sheet.md').includes('| 9') && files.get('c.sheet.md').endsWith('End\r\n'), JSON.stringify(files.get('c.sheet.md')));
files.set('bad.board.md', '```board\na: rect "A"\nthis is not a line\n```\n');
const kept = await run('add_shape', { path: 'bad.board.md', id: 'b' });
assert.equal(files.get('bad.board.md'), '```board\na: rect "A"\nb: rect\nthis is not a line\n```\n');
assert.match(kept.kept, /1 unreadable line/);
ok('CRLF files keep their line endings; an unreadable line is kept byte for byte and reported');
await assert.rejects(run('set_cells', { path: 's.sheet.md', cells: { A0: 1 } }), /cell address/);
await assert.rejects(run('add_sheet', { path: 's.sheet.md', name: 'a\nb' }), /one line/);
await assert.rejects(run('add_shape', { path: 'b.board.md', id: 'half', x: 5 }), /together/);
await assert.rejects(run('update_shape', { path: 'b.board.md', id: 'api', style: { fill: 'red}' } }), /not allowed/);
ok('bad addresses, multi-line sheet names, a lone x, and style text that would break a line are refused');
await assert.rejects(run('set_cells', { path: 's.sheet.md', cells: { XFD1048576: 1 } }), /cell address/);
await assert.rejects(run('add_shape', { path: 'b.board.md', id: 'bk', label: 'a\\' }), /backslash/);
await assert.rejects(run('add_shape', { path: 'b.board.md', id: 'bd', shape: 'class', body: ['x', ' ]'] }), /body line/);
await assert.rejects(run('add_sheet', { path: 's.sheet.md', name: '   ' }), /needs a name/);
await assert.rejects(run('add_sheet', { path: 's.sheet.md', name: ' Costs ' }), /already exists/);
await assert.rejects(run('add_sheet', { path: 's.sheet.md', name: 'Wide', rows: [new Array(300).fill('x')] }), /limited to/);
await assert.rejects(run('update_shape', { path: 'b.board.md', id: 'api', body: new Array(201).fill('x') }), /200 lines/);
await assert.rejects(run('update_shape', { path: 'b.board.md', id: 'api', label: 'a\rb' }), /carriage return/);
ok('huge addresses, backslash labels and a body line that would close the block are refused');
console.log(`\n${n} board and sheet tool checks passed`);
