// Folio — writes the generated reference pages in docs/reference/ from the code, so they cannot drift from it.
//   node scripts/docs-reference.mjs           write the pages
//   node scripts/docs-reference.mjs --check   fail if a page is out of date (run by npm test)
import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'); // also with spaces and drive letters
const check = process.argv.includes('--check');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'folio-docs-'));
await esbuild.build({
  stdin: { contents: "export { TOOLS } from './src/main/mcp-tools.js'; export { COMPONENTS, FEATURES } from './src/main/features/catalog.js'; export { z } from 'zod';", resolveDir: root, loader: 'js' },
  bundle: true, platform: 'node', format: 'esm', outfile: path.join(tmp, 'ref.mjs'), loader: { '.md': 'text' }, logLevel: 'silent',
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
});
const { TOOLS, COMPONENTS, FEATURES, z } = await import(pathToFileURL(path.join(tmp, 'ref.mjs')).href);
const head = (title, from) => `<!-- Generated by scripts/docs-reference.mjs from ${from}. Do not edit: run \`node scripts/docs-reference.mjs\`. -->\n\n# ${title}\n\n`;
const cell = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' '); // backslash first, then the table pipe

/* ---------- MCP tools ---------- */
function mcpTools() {
  let o = head('MCP tools', 'src/main/mcp-tools.js') + 'The tools Folio offers to AI assistants, over HTTP (in the app) and stdio (the bridge). Write tools run only when **Let AI edit notes** is on. *App only* tools need the app to be open.\n\n';
  o += '| Tool | Writes | Description |\n|---|---|---|\n';
  for (const t of TOOLS) o += `| \`${t.name}\`${t.appOnly ? ' *(app only)*' : ''} | ${t.write ? 'yes' : 'no'} | ${cell(t.description)} |\n`;
  for (const t of TOOLS) {
    const js = z.toJSONSchema(z.object(t.input || {}));
    const props = Object.entries(js.properties || {});
    o += `\n## \`${t.name}\`\n\n${t.description}\n\n`;
    if (!props.length) { o += 'No arguments.\n'; continue; }
    o += '| Argument | Type | Required | Description |\n|---|---|---|---|\n';
    for (const [k, v] of props) o += `| \`${k}\` | ${cell(v.enum ? v.enum.map((e) => `\`${e}\``).join(', ') : v.type || (v.anyOf ? 'any of several' : 'object'))} | ${(js.required || []).includes(k) ? 'yes' : 'no'} | ${cell(v.description)} |\n`;
  }
  return o;
}

/* ---------- IPC between the window and the main process ---------- */
function ipc() {
  const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
  const files = ['src/main/main.js', 'src/main/meeting/service.js'];
  const handled = new Map();
  for (const f of files) for (const m of read(f).matchAll(/(?:\bh|ipcMain\.(?:on|handle))\('([a-z0-9:-]+)'/g)) handled.set(m[1], f);
  const pre = read('src/main/preload.cjs');
  const api = [];
  let group = '';
  for (const line of pre.split('\n')) {
    const g = line.match(/^\s{2}([a-zA-Z]+): \{\s*$/); if (g) { group = g[1]; continue; }
    if (/^\s{2}\},?\s*$/.test(line)) { group = ''; continue; }
    const kindOf = (fn) => (fn === 'on' ? 'event' : fn === 'send' ? 'message' : 'request');
    const inline = line.match(/^\s{2}([a-zA-Z]+): \{(.+)\},?\s*$/); // a namespace on one line: qa: { start: …, poll: … }
    if (inline) {
      for (const m of inline[2].matchAll(/([a-zA-Z]+): \([^)]*\) => (call|send|on)\('([a-z0-9:-]+)'/g)) api.push({ name: `${inline[1]}.${m[1]}`, channel: m[3], kind: kindOf(m[2]) });
      continue;
    }
    const m = line.match(/^\s+([a-zA-Z]+):.*?\b(call|send|on)\('([a-z0-9:-]+)'/);
    if (m) api.push({ name: (group ? group + '.' : '') + m[1], channel: m[3], kind: kindOf(m[2]) });
  }
  let o = head('IPC: window ↔ main process', 'src/main/preload.cjs, src/main/main.js and src/main/meeting/service.js');
  o += 'The window has no Node.js. Everything it can ask of the main process is this list, exposed as `window.folio` by the preload script. Requests are answered by `h()` handlers, which accept calls only from the app page; events go from the main process to the window.\n\n';
  o += '| `window.folio.…` | Kind | Channel | Handled in |\n|---|---|---|---|\n';
  for (const a of api) o += `| \`${a.name}\` | ${a.kind} | \`${a.channel}\` | ${a.kind === 'event' ? '—' : handled.has(a.channel) ? `\`${handled.get(a.channel)}\`` : '**missing**'} |\n`;
  const unused = [...handled.keys()].filter((c) => !api.some((a) => a.channel === c));
  if (unused.length) o += `\nHandled but not exposed by name in the preload (used through a generic helper or by the menu): ${unused.map((c) => `\`${c}\``).join(', ')}.\n`;
  return o;
}

/* ---------- optional components ---------- */
function catalog() {
  const gb = (n) => (n >= 1e9 ? `${(n / 1e9).toFixed(2)} GB` : `${(n / 1e6).toFixed(1)} MB`);
  let o = head('Optional components', 'src/main/features/catalog.js');
  o += 'What an optional feature downloads. Every file has a fixed address (a commit, a version or a release tag) and a SHA-256 that is checked before the file is used, so a changed file is refused; nothing outside this list is ever downloaded. Components live in `%LOCALAPPDATA%\\Folio\\components` on Windows.\n\n';
  for (const [id, f] of Object.entries(FEATURES)) {
    o += `## Feature: ${f.name} (\`${id}\`)\n\n${f.description}\n\n- Platforms: ${f.platforms.join(', ')}\n- Memory budget: worker ${f.budget.workerMB} MB, whole app ${f.budget.appMB} MB\n- Required: ${f.required.map((c) => `\`${c}\``).join(', ')}\n- Notes (optional): ${f.notes.map((c) => `\`${c}\``).join(', ') || '—'}\n${f.optional ? `- Optional components: ${f.optional.map((c) => `\`${c}\``).join(', ')}\n` : ''}`;
    if (f.alternatives) o += `- Alternatives: ${Object.entries(f.alternatives).map(([k, v]) => `${k}: ${v.map((c) => `\`${c}\``).join(', ')}`).join('; ')}\n`;
    o += '\n';
  }
  o += '## Components\n\n| Id | Kind | Name | Version | License | Peak memory | Download (Windows x64) |\n|---|---|---|---|---|---|---|\n';
  for (const [id, c] of Object.entries(COMPONENTS)) {
    const files = c.files || c.platforms?.['win32-x64'] || [];
    o += `| \`${id}\` | ${c.kind} | ${cell(c.name)} | ${cell(c.version)} | ${c.license} | ${c.peakRamMB ? c.peakRamMB + ' MB' : '—'} | ${gb(files.reduce((n, x) => n + x.bytes, 0))} |\n`;
  }
  o += '\n## Attribution\n\n' + Object.values(COMPONENTS).map((c) => `- **${c.name}** — ${c.attribution} [License](${c.licenseUrl})`).join('\n') + '\n';
  return o;
}

const pages = { 'mcp-tools.md': mcpTools(), 'ipc.md': ipc(), 'components.md': catalog() };
const dir = path.join(root, 'docs', 'reference');
fs.mkdirSync(dir, { recursive: true });
let stale = [];
for (const [name, text] of Object.entries(pages)) {
  const file = path.join(dir, name);
  let cur = null; try { cur = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); } catch {} // read once; a Windows checkout may have CRLF
  if (cur === text) continue;
  if (check) stale.push(name); else fs.writeFileSync(file, text);
}
fs.rmSync(tmp, { recursive: true, force: true });
if (stale.length) { console.error(`docs/reference is out of date: ${stale.join(', ')}. Run: node scripts/docs-reference.mjs`); process.exit(1); }
console.log(check ? 'docs/reference is up to date' : `wrote docs/reference: ${Object.keys(pages).join(', ')}`);
